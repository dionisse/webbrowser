/**
 * `fr` is the source of truth for the key tree. Leaves are widened to `string`
 * so the English dictionary can hold different text while still being checked
 * key by key (a missing or extra key is a compile error).
 */
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? Widen<U>[]
    : { [K in keyof T]: Widen<T[K]> };

export type Dict = Widen<typeof fr>;
