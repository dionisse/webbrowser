import { config } from '../config.js';
import { createLogger } from '../lib/log.js';
import { EphemeralCache } from './cache.js';
import {
  extractReadable,
  PROXY_BASE,
  rewriteCss,
  rewriteHtml,
  type AssetKind,
  type ReaderArticle,
  type RewriteContext,
  type RewriteStats,
} from './rewrite.js';
import { isDemoUrl, renderDemo, resolveDemo } from './demo-sites.js';

const log = createLogger('browse');

/**
 * Upstream responses are cached, rewriting is done per request.
 *
 * Caching the *raw* bytes (rather than rewritten HTML) matters: rewritten URLs
 * embed a per-session token, so a rewritten document must never be shared
 * between sessions. Rewriting costs a few milliseconds and keeps the cache
 * session-agnostic.
 */
export const cache = new EphemeralCache(config.browse.cacheTtlSeconds * 1000);

export interface BrowseOptions {
  mode: 'document' | AssetKind;
  blockTrackers: boolean;
  hideNuisance: boolean;
  reader: boolean;
  method?: 'GET' | 'POST';
  body?: string;
  contentType?: string;
  noCache?: boolean;
  /** Per-session token stamped into every rewritten URL. */
  token?: string;
}

export interface BrowseFailure {
  kind: 'blocked' | 'unreachable' | 'unsupported' | 'too_large' | 'timeout' | 'http';
  status?: number;
  message: string;
  url: string;
  hint?: string;
}

export interface BrowseSuccess {
  kind: 'html' | 'asset' | 'reader' | 'download';
  status: number;
  url: string;
  finalUrl: string;
  contentType: string;
  title?: string;
  stats?: RewriteStats;
  html?: string;
  reader?: ReaderArticle;
  body?: Buffer;
  disposition?: string;
  fromCache?: boolean;
  blockedHosts?: string[];
}

export type BrowseResult = { ok: true; value: BrowseSuccess } | { ok: false; error: BrowseFailure };

function isHostBlocked(url: URL): boolean {
  const host = url.hostname.toLowerCase();
  if (!['http:', 'https:'].includes(url.protocol)) return true;
  if (host === 'localhost' || host.endsWith('.localhost') || host === '[::1]') return true;
  // The engine runs inside a cloud VPC: refuse private, loopback and metadata
  // ranges so it can never be used as an SSRF pivot.
  if (/^(\d{1,3}\.){3}\d{1,3}$/.test(host)) {
    const parts = host.split('.').map(Number) as [number, number, number, number];
    const [a, b] = parts;
    if (a === 10 || a === 127 || a === 0 || (a === 192 && b === 168) || (a === 172 && b >= 16 && b <= 31) || (a === 169 && b === 254)) {
      return true;
    }
  }
  if (host.includes(':') && !host.startsWith('[')) return true;
  return config.browse.blockedHosts.some((h) => host === h || host.endsWith(`.${h}`));
}

export function normaliseInput(input: string): URL | null {
  const trimmed = input.trim();
  if (!trimmed) return null;
  const withScheme = /^[a-z][a-z0-9+.-]*:\/\//i.test(trimmed) ? trimmed : `https://${trimmed}`;
  try {
    const url = new URL(withScheme);
    if (!['http:', 'https:'].includes(url.protocol)) return null;
    return url;
  } catch {
    return null;
  }
}

/** Accept raw target URLs and our own proxy URLs (pasted back into the omnibox). */
export function unwrapProxyUrl(input: string): string {
  try {
    const u = new URL(input, 'http://nimbus.local');
    if (u.pathname.startsWith(`${PROXY_BASE}/`)) {
      const inner = u.searchParams.get('u');
      if (inner) return inner;
    }
  } catch {
    /* fall through */
  }
  return input;
}

async function fetchUpstream(url: URL, opts: BrowseOptions): Promise<Response> {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), config.browse.timeoutMs);
  try {
    return await fetch(url, {
      method: opts.method ?? 'GET',
      headers: {
        'user-agent': config.browse.userAgent,
        accept:
          opts.mode === 'document'
            ? 'text/html,application/xhtml+xml,application/xml;q=0.9,image/avif,image/webp,*/*;q=0.8'
            : '*/*',
        'accept-language': 'fr-FR,fr;q=0.9,en;q=0.8',
        ...(opts.body ? { 'content-type': opts.contentType ?? 'application/x-www-form-urlencoded' } : {}),
      },
      body: opts.body,
      redirect: 'follow',
      signal: controller.signal,
    });
  } finally {
    clearTimeout(timer);
  }
}

export async function browse(rawTarget: string, opts: BrowseOptions): Promise<BrowseResult> {
  const target = unwrapProxyUrl(rawTarget);

  // Internal demo pages: generated by the engine, but run through the exact
  // same rewriter, blocker and shim as a real site.
  if (isDemoUrl(target)) {
    const resolved = resolveDemo(target);
    if (!resolved) return { ok: false, error: { kind: 'unsupported', message: 'Page de démonstration inconnue', url: target } };
    if (opts.mode !== 'document') {
      return { ok: true, value: { kind: 'asset', status: 404, url: target, finalUrl: resolved.url.href, contentType: 'text/plain', body: Buffer.alloc(0) } };
    }
    if (opts.reader) {
      const reader = extractReadable(resolved.page.html, resolved.url);
      return {
        ok: true,
        value: { kind: 'reader', status: 200, url: target, finalUrl: target, contentType: 'application/json', title: reader.title, reader },
      };
    }
    const rendered = renderDemo(target, { token: opts.token, blockTrackers: opts.blockTrackers, hideNuisance: opts.hideNuisance });
    if (!rendered) return { ok: false, error: { kind: 'unsupported', message: 'Rendu de démonstration impossible', url: target } };
    return {
      ok: true,
      value: {
        kind: 'html',
        status: 200,
        url: target,
        finalUrl: target,
        contentType: 'text/html; charset=utf-8',
        title: rendered.title,
        stats: rendered.stats,
        html: rendered.html,
        blockedHosts: [...new Set(rendered.stats.blockedHosts)],
        body: Buffer.from(rendered.html, 'utf8'),
      },
    };
  }

  const url = normaliseInput(target);
  if (!url) {
    return { ok: false, error: { kind: 'unsupported', message: 'Adresse invalide', url: target, hint: 'check_url' } };
  }
  if (isHostBlocked(url)) {
    return {
      ok: false,
      error: { kind: 'blocked', message: 'Hôte refusé par la politique du moteur cloud', url: url.href, hint: 'host_policy' },
    };
  }

  const cacheKey = `${opts.mode}|${opts.method ?? 'GET'}|${url.href}`;
  let res: Response | undefined;
  let cached: { body: Buffer; mimeType: string; status: number; finalUrl: string; disposition?: string } | undefined;

  if (!opts.noCache && opts.method !== 'POST') {
    const hit = cache.get(cacheKey);
    if (hit) {
      const [mimeType, meta] = hit.mimeType.split('\n');
      const parsed = meta ? (JSON.parse(meta) as { finalUrl: string; disposition?: string }) : { finalUrl: url.href };
      cached = { body: hit.body, mimeType: mimeType!, status: hit.status, finalUrl: parsed.finalUrl, disposition: parsed.disposition };
    }
  }

  if (cached) {
    res = undefined;
  } else {
    try {
      res = await fetchUpstream(url, opts);
    } catch (err) {
      const aborted = (err as Error).name === 'AbortError';
      return {
        ok: false,
        error: {
          kind: aborted ? 'timeout' : 'unreachable',
          message: aborted ? 'Délai dépassé' : `Impossible de joindre ${url.hostname}`,
          url: url.href,
          hint: (err as Error).message?.slice(0, 200),
        },
      };
    }
  }

  const finalUrl = cached ? new URL(cached.finalUrl) : res!.url ? new URL(res!.url) : url;
  const rawContentType = cached ? cached.mimeType : ((res!.headers.get('content-type') ?? '').split(';')[0]?.trim().toLowerCase() ?? '');
  const disposition = cached ? cached.disposition : (res!.headers.get('content-disposition') ?? undefined);
  const status = cached ? cached.status : res!.status;

  if (!cached && !res!.ok && res!.status >= 400 && opts.mode === 'document') {
    const body = await safeText(res!);
    log.warn(`upstream ${res!.status} for ${url.href}`);
    return {
      ok: false,
      error: {
        kind: 'http',
        status: res!.status,
        message: `${res!.status} ${res!.statusText || ''}`.trim(),
        url: url.href,
        hint: body?.slice(0, 300),
      },
    };
  }

  let buf = cached?.body;
  if (!buf) {
    const lengthHeader = Number(res!.headers.get('content-length') ?? 0);
    if (lengthHeader > config.browse.maxDocumentBytes) {
      return { ok: false, error: { kind: 'too_large', message: `Document trop volumineux (${lengthHeader} octets)`, url: url.href } };
    }
    buf = Buffer.from(await res!.arrayBuffer());
    if (buf.length > config.browse.maxDocumentBytes) {
      return { ok: false, error: { kind: 'too_large', message: `Document trop volumineux (${buf.length} octets)`, url: url.href } };
    }
    const store = (mimeType: string) =>
      cache.set(
        cacheKey,
        buf!,
        `${mimeType}\n${JSON.stringify({ finalUrl: finalUrl.href, disposition })}`,
        status,
      );
    store(rawContentType || 'application/octet-stream');
  }

  const ctx: RewriteContext = {
    pageUrl: finalUrl,
    blockTrackers: opts.blockTrackers,
    hideNuisance: opts.hideNuisance,
    injectRuntime: true,
    token: opts.token,
  };

  const isHtml = rawContentType.includes('html') || rawContentType === '' || rawContentType.includes('xml');
  const isCss = rawContentType.includes('css');
  const isJs = rawContentType.includes('javascript') || rawContentType.includes('ecmascript');

  // ---- Assets -------------------------------------------------------------
  if (opts.mode === 'raw' || (opts.mode !== 'document' && !isHtml && !isCss && !isJs)) {
    return {
      ok: true,
      value: {
        kind: 'asset',
        status,
        url: url.href,
        finalUrl: finalUrl.href,
        contentType: rawContentType || 'application/octet-stream',
        body: buf,
        disposition,
        fromCache: Boolean(cached),
      },
    };
  }

  if (opts.mode === 'css' || isCss) {
    const stats: RewriteStats = { urlsRewritten: 0, trackersBlocked: 0, blockedHosts: [] };
    const css = rewriteCss(buf.toString('utf8'), ctx, stats);
    return {
      ok: true,
      value: {
        kind: 'asset',
        status,
        url: url.href,
        finalUrl: finalUrl.href,
        contentType: 'text/css; charset=utf-8',
        body: Buffer.from(css, 'utf8'),
        stats,
        blockedHosts: stats.blockedHosts,
        fromCache: Boolean(cached),
      },
    };
  }

  if (opts.mode === 'js' || isJs) {
    // Scripts pass through untouched: rewriting JS safely needs a real parser.
    // Trackers are already severed at the HTML layer, and the sandboxed frame
    // cannot reach the Nimbus origin anyway.
    return {
      ok: true,
      value: {
        kind: 'asset',
        status,
        url: url.href,
        finalUrl: finalUrl.href,
        contentType: 'application/javascript; charset=utf-8',
        body: buf,
        fromCache: Boolean(cached),
      },
    };
  }

  // ---- Documents ----------------------------------------------------------
  const html = buf.toString('utf8');

  if (opts.reader) {
    const reader = extractReadable(html, finalUrl);
    return {
      ok: true,
      value: {
        kind: 'reader',
        status,
        url: url.href,
        finalUrl: finalUrl.href,
        contentType: 'application/json',
        title: reader.title,
        reader,
        fromCache: Boolean(cached),
      },
    };
  }

  const rewritten = rewriteHtml(html, ctx);
  log.debug(`rendered ${finalUrl.href} — ${rewritten.stats.urlsRewritten} urls rewritten, ${rewritten.stats.trackersBlocked} trackers cut`);
  return {
    ok: true,
    value: {
      kind: 'html',
      status,
      url: url.href,
      finalUrl: finalUrl.href,
      contentType: 'text/html; charset=utf-8',
      title: rewritten.title,
      stats: rewritten.stats,
      html: rewritten.html,
      blockedHosts: [...new Set(rewritten.stats.blockedHosts)],
      body: Buffer.from(rewritten.html, 'utf8'),
      fromCache: Boolean(cached),
    },
  };
}

async function safeText(res: Response): Promise<string | undefined> {
  try {
    return (await res.text()).slice(0, 2000);
  } catch {
    return undefined;
  }
}
